"""Synthetic school-district finance generator.

DISCLOSURE: All data is SYNTHETIC, generated by a seeded random process.
It is NOT the real finances of Phoenix Central School District or any real
district. Fund categories follow standard governmental fund-accounting
structure as a labelled [ASSUMPTION] — this is NOT Wincap expertise and
must not be presented as such.

World: 8 fiscal years of history (FY2018-FY2025) + forecast horizon FY2026-28.
Departments, revenue sources, enrollment, staffing, and fund balance are
generated with realistic dynamics (NY tax-cap ~2% levy growth, state-aid
growth, faster benefits growth, a temporary federal-aid bump that rolls off,
and a slowly declining enrollment).
"""
from __future__ import annotations

import numpy as np
import pandas as pd

SEED = 42

DEPARTMENTS = [
    "Instruction",
    "Special Education",
    "Transportation",
    "Operations & Maintenance",
    "Administration",
    "Employee Benefits",
    "Debt Service",
    "Food Service & Other",
]

REVENUE_SOURCES = ["Property Tax Levy", "State Aid", "Federal Aid", "Other Local Revenue"]

YEARS = list(range(2018, 2026))          # history FY2018-FY2025
FORECAST_YEARS = [2026, 2027, 2028]

# Injected variance anomalies: (year, department, actual-vs-adopted pct).
# Kept as ground truth for the anomaly-detection evaluation.
INJECTED_ANOMALIES = [
    (2021, "Transportation", 0.092),
    (2023, "Special Education", 0.078),
    (2024, "Operations & Maintenance", -0.071),
]


def generate(seed: int = SEED) -> dict[str, pd.DataFrame]:
    rng = np.random.default_rng(seed)

    # --- Enrollment: ~3,400 pupils, declining ~0.8%/yr with noise ---
    enrollment = []
    pupils = 3420.0
    for _ in YEARS:
        enrollment.append(pupils)
        pupils *= 1 - 0.008 + rng.normal(0, 0.003)
    enrollment = np.array(enrollment)

    # --- Revenue ---
    levy = [18_400_000.0]
    for _ in range(1, len(YEARS)):
        levy.append(levy[-1] * (1 + 0.019 + rng.normal(0, 0.004)))
    levy = np.array(levy)

    state_aid = [15_100_000.0]
    for _ in range(1, len(YEARS)):
        state_aid.append(state_aid[-1] * (1 + 0.025 + rng.normal(0, 0.008)))
    state_aid = np.array(state_aid)

    # Federal aid: ESSER-style bump FY2021-22, then rolls off.
    federal_base = np.array([2_100_000, 2_150_000, 2_200_000, 4_900_000,
                             5_300_000, 2_350_000, 2_400_000, 2_450_000], dtype=float)
    federal = federal_base * (1 + rng.normal(0, 0.02, len(YEARS)))

    other_local = np.array([1_900_000.0]) * (1 + np.cumsum(rng.normal(0.015, 0.02, len(YEARS))))
    other_local = np.maximum(other_local, 1_200_000)

    revenue = pd.DataFrame({
        "fiscal_year": YEARS,
        "enrollment": enrollment.round(0).astype(int),
        "Property Tax Levy": levy,
        "State Aid": state_aid,
        "Federal Aid": federal,
        "Other Local Revenue": other_local,
    })
    revenue["Total Revenue"] = revenue[REVENUE_SOURCES].sum(axis=1)

    # --- Expenditure: adopted budget by department ---
    # Department shares of the adopted budget (stable-ish, drift slowly).
    shares = {
        "Instruction": 0.46,
        "Special Education": 0.16,
        "Transportation": 0.07,
        "Operations & Maintenance": 0.08,
        "Administration": 0.05,
        "Employee Benefits": 0.12,
        "Debt Service": 0.04,
        "Food Service & Other": 0.02,
    }
    # Total adopted budget grows ~3.1%/yr (salaries 2.8%, benefits 4.5% blended).
    total_adopted = [37_200_000.0]
    for _ in range(1, len(YEARS)):
        total_adopted.append(total_adopted[-1] * (1 + 0.031 + rng.normal(0, 0.006)))
    total_adopted = np.array(total_adopted)

    rows = []
    anomaly_lookup = {(y, d): pct for y, d, pct in INJECTED_ANOMALIES}
    for i, year in enumerate(YEARS):
        for dept in DEPARTMENTS:
            share = shares[dept] * (1 + rng.normal(0, 0.01))
            adopted = total_adopted[i] * share
            # Actual vs adopted: small noise, plus injected anomalies.
            var = rng.normal(0, 0.018)
            if (year, dept) in anomaly_lookup:
                var = anomaly_lookup[(year, dept)] + rng.normal(0, 0.004)
            actual = adopted * (1 + var)
            rows.append({
                "fiscal_year": year,
                "department": dept,
                "adopted_budget": round(adopted, 2),
                "actual_expenditure": round(actual, 2),
                "variance_pct": round(var, 4),
                "injected_anomaly": int((year, dept) in anomaly_lookup),
            })
    expenditure = pd.DataFrame(rows)
    expenditure["Total Actual"] = expenditure.groupby("fiscal_year")["actual_expenditure"].transform("sum")
    expenditure["Total Adopted"] = expenditure.groupby("fiscal_year")["adopted_budget"].transform("sum")

    # --- Staffing ---
    fte = [415.0]
    for _ in range(1, len(YEARS)):
        fte.append(fte[-1] * (1 - 0.004 + rng.normal(0, 0.004)))
    fte = np.array(fte)
    avg_salary = [68_500.0]
    for _ in range(1, len(YEARS)):
        avg_salary.append(avg_salary[-1] * (1 + 0.028 + rng.normal(0, 0.004)))
    avg_salary = np.array(avg_salary)
    benefit_rate = [0.34]
    for _ in range(1, len(YEARS)):
        benefit_rate.append(min(benefit_rate[-1] * (1 + 0.045 + rng.normal(0, 0.005)), 0.62))
    benefit_rate = np.array(benefit_rate)
    staffing = pd.DataFrame({
        "fiscal_year": YEARS,
        "fte": fte.round(1),
        "avg_salary": avg_salary.round(0),
        "benefit_rate": benefit_rate.round(4),
        "enrollment": enrollment.round(0).astype(int),
    })
    staffing["salary_cost"] = (staffing["fte"] * staffing["avg_salary"]).round(0)
    staffing["benefit_cost"] = (staffing["salary_cost"] * staffing["benefit_rate"]).round(0)
    staffing["total_staffing_cost"] = staffing["salary_cost"] + staffing["benefit_cost"]
    staffing["pupils_per_fte"] = (staffing["enrollment"] / staffing["fte"]).round(2)

    # --- Fund balance ---
    fund_rows = []
    fund_balance = 6_500_000.0
    for i, year in enumerate(YEARS):
        rev = revenue.loc[i, "Total Revenue"]
        exp = expenditure.loc[expenditure["fiscal_year"] == year, "actual_expenditure"].sum()
        net = rev - exp
        fund_balance += net
        fund_rows.append({
            "fiscal_year": year,
            "total_revenue": round(rev, 2),
            "total_expenditure": round(exp, 2),
            "operating_surplus_deficit": round(net, 2),
            "fund_balance_eoy": round(fund_balance, 2),
            "fund_balance_pct_of_next_budget": None,  # filled below
        })
    fund = pd.DataFrame(fund_rows)
    for i in range(len(fund) - 1):
        nxt = expenditure.loc[expenditure["fiscal_year"] == YEARS[i + 1], "adopted_budget"].sum()
        fund.loc[i, "fund_balance_pct_of_next_budget"] = round(
            100 * fund.loc[i, "fund_balance_eoy"] / nxt, 2)
    fund.loc[len(fund) - 1, "fund_balance_pct_of_next_budget"] = round(
        100 * fund.loc[len(fund) - 1, "fund_balance_eoy"]
        / (fund.loc[len(fund) - 1, "total_expenditure"] * 1.031), 2)

    return {
        "revenue": revenue,
        "expenditure": expenditure,
        "staffing": staffing,
        "fund": fund,
        "anomalies": pd.DataFrame(
            INJECTED_ANOMALIES, columns=["fiscal_year", "department", "variance_pct"]),
    }


if __name__ == "__main__":
    data = generate()
    for name, df in data.items():
        print(f"--- {name}: {df.shape} ---")
        print(df.head(3).to_string(index=False))
